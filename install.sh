#!/usr/bin/env bash
# sadWatcher Installer
# https://github.com/horamsafaryani/sadWatcher

set -e

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

INSTALL_DIR="/var/lib/sadWatcher"
SERVICE_NAME="sadWatcher"
BINARY_NAME="sadWatcher"
GITHUB_REPO="horamsafaryani/sadWatcher"

# ─── helpers ──────────────────────────────────────────────────────────────────

info()    { echo -e "${CYAN}[INFO]${NC}  $*"; }
success() { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
error()   { echo -e "${RED}[ERROR]${NC} $*"; exit 1; }

ask() {
    local prompt="$1"
    local default="$2"
    local answer
    if [[ -n "$default" ]]; then
        read -rp "$(echo -e "${BOLD}$prompt${NC} [${default}]: ")" answer
        echo "${answer:-$default}"
    else
        read -rp "$(echo -e "${BOLD}$prompt${NC}: ")" answer
        echo "$answer"
    fi
}

check_root() {
    [[ "$EUID" -eq 0 ]] || error "Please run as root"
}

